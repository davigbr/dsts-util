const LANGS = [
  { id: "en", label: "EN" },
  { id: "pt", label: "PT" },
];

let LANG = "en";

function t(key, vars) {
  const dict = LOCALES[LANG] || LOCALES.en;
  let s = dict[key];
  if (s == null) s = LOCALES.en[key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? "" : String(vars[k])));
  return s;
}

/* aplica tradução em nós estáticos marcados no HTML */
function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach(e => {
    const v = t(e.dataset.i18n);
    if (v != null) e.textContent = v;
  });
  scope.querySelectorAll("[data-i18n-ph]").forEach(e => { e.placeholder = t(e.dataset.i18nPh); });
  scope.querySelectorAll("[data-i18n-title]").forEach(e => { e.title = t(e.dataset.i18nTitle); });
  document.documentElement.lang = LANG === "pt" ? "pt-BR" : "en";
  document.title = t("app.title");
}

/* troca de idioma: re-traduz o estático e redesenha o que está na tela */
function setLang(lang, opts = {}) {
  LANG = LOCALES[lang] ? lang : "en";
  try { localStorage.setItem("dvz.lang", LANG); } catch (e) {}
  applyI18n();
  if (opts.rerender !== false && typeof rerenderAll === "function") rerenderAll();
}

function initLang() {
  let saved = null;
  try { saved = localStorage.getItem("dvz.lang"); } catch (e) {}
  if (saved && LOCALES[saved]) LANG = saved;
  else LANG = "en";
}
